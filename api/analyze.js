export default async function handler(req, res) {
  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader("Access-Control-Allow-Methods", "POST, OPTIONS");
  res.setHeader("Access-Control-Allow-Headers", "Content-Type");

  if (req.method === "OPTIONS") return res.status(200).end();
  if (req.method !== "POST") return res.status(405).json({ error: "Method not allowed" });

  try {
    const { candidate } = req.body;
    const score = Number(candidate["Балл % (макс 100)"]) || 0;

    const prompt = `Ты — опытный HR-директор в области закупок и снабжения. Твоя задача — дать честную, объективную оценку кандидата без приукрашивания. Результаты должны точно отражать реальный уровень кандидата.

Данные кандидата:
- Имя: ${candidate["Имя"]}
- Общий балл: ${score}% (${candidate["Ранг"]})
- Числовая логика: ${candidate["Числовая логика (макс 8)"]}/8 (${Math.round((Number(candidate["Числовая логика (макс 8)"]) / 8) * 100)}%)
- Вербальное мышление: ${candidate["Вербальное мышление (макс 8)"]}/8 (${Math.round((Number(candidate["Вербальное мышление (макс 8)"]) / 8) * 100)}%)
- Ситуативные задачи: ${candidate["Ситуативные задачи (макс 12)"]}/12 (${Math.round((Number(candidate["Ситуативные задачи (макс 12)"]) / 12) * 100)}%)
- Нестандартное мышление: ${candidate["Нестандартное мышление (макс 8)"]}/8 (${Math.round((Number(candidate["Нестандартное мышление (макс 8)"]) / 8) * 100)}%)
- Скорость решений: ${candidate["Скорость решений (макс 7)"]}/7 (${Math.round((Number(candidate["Скорость решений (макс 7)"]) / 7) * 100)}%)
- DISC профиль (основной): ${candidate["DISC осн."]}
- DISC профиль (вторичный): ${candidate["DISC втор."]}
- Командная роль по Белбину (основная): ${candidate["Белбин осн."]}
- Командная роль по Белбину (вторичная): ${candidate["Белбин втор."]}

Шкала оценки секций:
- 0-40%: критически слабый результат — серьёзный риск для найма
- 41-55%: ниже ожиданий — значительные пробелы
- 56-70%: средний уровень — базовые компетенции присутствуют
- 71-85%: хороший уровень — уверенные компетенции
- 86-100%: отличный результат — высокий потенциал

Контекст: отдел закупок и снабжения крупной компании. Группы: управление мастер-данными ERP, снабжение (indirect purchasing), проектные закупки (direct purchasing), качество поставщиков и рекламации, системные компоненты.

Напиши честный анализ из 4 абзацев:

1. Общая картина — объективная оценка уровня кандидата. Если результаты слабые — скажи это прямо. Не смягчай.

2. Что работает — только реально подтверждённые данными сильные стороны. Если секция ниже 60% — она НЕ является сильной стороной даже если DISC профиль намекает на потенциал.

3. Критические пробелы — конкретно назови какие секции провалены и что это означает для реальной работы в закупках. Будь прямым.

4. Вывод для HR — чёткая рекомендация: брать / не брать / брать с условиями. Если общий балл ниже 45% — рекомендуй отказать или провести дополнительное собеседование с конкретными проверками.

Тон: профессиональный, прямой, без лишнего оптимизма. Факты важнее дипломатии.`;

    const response = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "x-api-key": process.env.ANTHROPIC_API_KEY,
        "anthropic-version": "2023-06-01"
      },
      body: JSON.stringify({
        model: "claude-haiku-4-5-20251001",
        max_tokens: 1000,
        messages: [{ role: "user", content: prompt }]
      })
    });

    const data = await response.json();
    const text = data.content?.map(b => b.text || "").join("") || "Не удалось получить анализ.";
    res.status(200).json({ result: text });
  } catch (e) {
    res.status(500).json({ error: e.message });
  }
}